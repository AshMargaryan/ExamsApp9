def build_exam(idx):
    C.CUR = []
    C._pos_counter = idx
    n = 1
    for t in SC_TEMPLATES:
        t(n); n += 1
    for f in FR_TEMPLATES:
        f(n); n += 1
    for g in GROUPS:
        g(n)
        n = C.CUR[-1]["number"] + 1
    t68(n); n += 1
    ms69(n); n += 1
    ms70(n); n += 1
    nums = [q["number"] for q in C.CUR]
    assert nums == list(range(1, 71)), (idx, nums)
    return {"exam_id": f"AEE-CHEM-{idx:03d}", "title": f"Միասնական քննություն — Քիմիա (թեստ {idx})",
            "question_count": 70, "subject": "chemistry", "questions": C.CUR}

def sig(q):
    return (q["question"] + "|" + q.get("figure_svg", "") + "|" +
            "".join(q.get("options", [])) + "|" + str(q.get("answer", "")) +
            "|" + "".join(q.get("statements", [])))

