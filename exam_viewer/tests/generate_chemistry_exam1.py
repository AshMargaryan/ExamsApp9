# ---- export $...$ segments for KaTeX validation ----
import re
MATH_SPLIT = re.compile(r"(\$\$[\s\S]+?\$\$|\$[^$\n]+?\$)")
segs = []
for q in CUR:
    texts = [q["question"], q.get("hint", "")] + q.get("solution_steps", [])
    if q["type"] == "single_choice":
        texts += q["options"]
    if q["type"] == "multi_statement":
        texts += q["statements"]
    for t in texts:
        for part in MATH_SPLIT.findall(t):
            segs.append({"n": q["number"], "seg": part[1:-1] if not part.startswith("$$") else part[2:-2]})
segs_path = os.path.join(os.path.dirname(__file__), "_chem_katex_segs.json")
with open(segs_path, "w", encoding="utf-8") as f:
    json.dump(segs, f, ensure_ascii=False)
print(f"Wrote {len(segs)} KaTeX segments to {segs_path}")

