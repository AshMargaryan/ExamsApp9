def _esc(s):
    return (s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;"))


def svg_lines(rows, width=560, fs=15, lh=27, pad=14):
    """Single-column list of text rows (for ordering step-lists)."""
    height = pad * 2 + lh * len(rows)
    y = pad + fs
    body = []
    for r in rows:
        body.append(
            f'<text x="{pad}" y="{y}" font-family="Arial, \'Noto Sans Armenian\', sans-serif" '
            f'font-size="{fs}" fill="#111111">{_esc(r)}</text>'
        )
        y += lh
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="{width}" height="{height}">{"".join(body)}</svg>'
    )


def svg_match(header_left, left_rows, header_right, right_rows,
              width=660, fs=15, lh=27, pad=14, split=330):
    """Two-column matching table: left items (Ա,Բ...) and right categories (1,2..)."""
    n = max(len(left_rows), len(right_rows))
    height = pad * 2 + lh * (n + 1)
    body = [
        f'<text x="{pad}" y="{pad + fs}" font-family="Arial, \'Noto Sans Armenian\', sans-serif" '
        f'font-size="{fs}" font-weight="bold" fill="#111111">{_esc(header_left)}</text>',
        f'<text x="{split + pad}" y="{pad + fs}" font-family="Arial, \'Noto Sans Armenian\', sans-serif" '
        f'font-size="{fs}" font-weight="bold" fill="#111111">{_esc(header_right)}</text>',
        f'<line x1="{split}" y1="{pad}" x2="{split}" y2="{height - pad}" stroke="#cccccc" stroke-width="1"/>',
    ]
    y = pad + fs + lh
    for r in left_rows:
        body.append(
            f'<text x="{pad}" y="{y}" font-family="Arial, \'Noto Sans Armenian\', sans-serif" '
            f'font-size="{fs}" fill="#111111">{_esc(r)}</text>'
        )
        y += lh
    y = pad + fs + lh
    for r in right_rows:
        body.append(
            f'<text x="{split + pad}" y="{y}" font-family="Arial, \'Noto Sans Armenian\', sans-serif" '
            f'font-size="{fs}" fill="#111111">{_esc(r)}</text>'
        )
        y += lh
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" '
        f'width="{width}" height="{height}">{"".join(body)}</svg>'
    )


def html_match(header_left, left_rows, header_right, right_rows):
    """Two-column matching table rendered as real HTML text (not an image).
    Goes in the figure_svg field; QuestionFigure injects it as HTML."""
    n = max(len(left_rows), len(right_rows))
    th = ('style="text-align:left;padding:6px 28px 10px 0;border-bottom:1px solid #bbb;'
          'font-weight:bold;white-space:nowrap"')
    td = 'style="text-align:left;padding:5px 28px 5px 0;vertical-align:top"'
    rows = [f'<tr><th {th}>{_esc(header_left)}</th><th {th}>{_esc(header_right)}</th></tr>']
    for i in range(n):
        left = _esc(left_rows[i]) if i < len(left_rows) else ""
        right = _esc(right_rows[i]) if i < len(right_rows) else ""
        rows.append(f'<tr><td {td}>{left}</td><td {td}>{right}</td></tr>')
    return ('<table style="border-collapse:collapse;font-family:Arial,sans-serif;'
            'font-size:15px;color:#111111">' + "".join(rows) + '</table>')


